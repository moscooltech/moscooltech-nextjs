#!/usr/bin/env node
/**
 * Build db/seed.sql from db/seed-data.json (Converted from the Flask app's
 * seed_data.py so the copy and the content stay identical).
 *
 * Usage: node scripts/build-seed-sql.mjs
 * Apply: npm run db:seed        (remote)
 *        npm run db:seed:local  (local D1 during development)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const { portfolio, articles } = JSON.parse(readFileSync(join(root, "db/seed-data.json"), "utf8"));

const q = (value) => (value === null || value === undefined ? "NULL" : `'${String(value).replace(/'/g, "''")}'`);
const slugify = (title) =>
  title.toLowerCase().replace(/\s+/g, "-").replace(/[^a-z0-9-]/g, "").slice(0, 250) || "article";

const rows = [];
const faqRows = [];

const push = (post, type, slug) => {
  rows.push(
    `INSERT INTO posts (title, slug, content, meta_description, image_url, image_alt, category, post_type, published)\n` +
      `VALUES (${q(post.title)}, ${q(slug)}, ${q(post.content)}, ${q((post.meta_description || "").slice(0, 160))}, ` +
      `${q(post.image)}, ${q(post.image_alt || post.title)}, ${q(post.category || (type === "article" ? "guides" : "general"))}, ` +
      `${q(type)}, 1)\nON CONFLICT(slug) DO NOTHING;`,
  );
  for (const [position, faq] of (post.faqs || []).entries()) {
    faqRows.push(
      `INSERT INTO post_faqs (post_id, question, answer, position) SELECT id, ${q(faq.q)}, ${q(faq.a)}, ${position} ` +
        `FROM posts WHERE slug = ${q(slug)};\n`,
    );
  }
};

for (const post of portfolio) push(post, "portfolio", slugify(post.title));
for (const article of articles) push(article, "article", article.slug);

const sql = [
  "-- Generated by scripts/build-seed-sql.mjs — do not edit by hand.",
  "-- Idempotent: safe to run more than once.",
  "PRAGMA foreign_keys = ON;",
  "",
  ...rows,
  "",
  ...faqRows,
  "",
].join("\n");

writeFileSync(join(root, "db/seed.sql"), sql);
console.log(`seed.sql written: ${rows.length} posts, ${faqRows.length} FAQs`);
